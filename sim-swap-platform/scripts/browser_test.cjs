const fs=require('node:fs');
const {chromium}=require(process.env.CODEX_PRIMARY_RUNTIME_NODE_MODULES?process.env.CODEX_PRIMARY_RUNTIME_NODE_MODULES+'/playwright':'playwright');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_EXECUTABLE_PATH||undefined,args:['--no-sandbox','--disable-dev-shm-usage']});
 const page=await browser.newPage({viewport:{width:1440,height:1050}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(process.env.TEST_URL||'http://127.0.0.1:8000');
 await page.getByLabel('Access token').fill(process.env.TEST_TOKEN);
 await page.getByRole('button',{name:'Open workspace'}).click();
 await page.getByRole('heading',{name:'Fraud operations',exact:true}).waitFor();
 await page.getByText('Current workspace').first().waitFor();
 await page.getByRole('button',{name:'↻ Refresh',exact:true}).waitFor();
 await page.screenshot({path:'reports/dashboard.png',fullPage:true});
 await page.getByRole('button',{name:'Cases',exact:true}).click();
 await page.getByRole('button',{name:'Investigate'}).first().click();
 await page.getByRole('dialog').waitFor();
 await page.getByLabel('Investigation note').fill('Browser smoke test investigation note');
 await page.getByRole('button',{name:'Save investigation'}).click();
 await page.getByText('Case saved with an audited version update.').first().waitFor();
 await page.getByRole('button',{name:'Close details'}).click();
 await page.getByRole('button',{name:'Models',exact:true}).click();
 await page.getByText('demo-logistic-v1',{exact:true}).waitFor();
 await page.getByRole('button',{name:'Select for shadow'}).first().click();
 await page.getByText('Shadow model selected. Rules still drive recommendations.').waitFor();
 await page.getByRole('button',{name:'Assess',exact:true}).click();
 await page.getByLabel('Subscriber',{exact:true}).fill('browser-synthetic-user');
 await page.getByLabel('Action ID',{exact:true}).fill('browser-action');
 await page.getByLabel('Device ID',{exact:true}).fill('new-device');
 await page.getByRole('button',{name:'Assess action'}).click();
 await page.getByRole('dialog').waitFor();
 await page.getByRole('button',{name:'Close details'}).click();
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'Overview',exact:true}).click();
 await page.getByRole('heading',{name:'Fraud operations',exact:true}).waitFor();
 await page.getByRole('button',{name:'↻ Refresh',exact:true}).waitFor();
 await page.screenshot({path:'reports/dashboard-mobile.png',fullPage:true});
 fs.writeFileSync('reports/browser-test.json',JSON.stringify({passed:errors.length===0,checks:['login','dashboard','case investigation saved','shadow model selected','assessment submitted','mobile layout'],page_errors:errors},null,2));
 await browser.close();
 if(errors.length)throw new Error(errors.join('\n'));
 console.log('Browser workflow checks passed.');
})().catch(e=>{console.error(e.message);process.exit(1)});
